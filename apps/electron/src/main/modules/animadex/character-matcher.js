/**
 * 本地角色名称匹配：精确名、已收录别名、片段、单处拼写差异依次查找。
 * 像先按身份证找人，再看登记昵称，最后才给相近名字的候选名单。
 * 只有前一层没有命中才进入下一层，热度不能压过明确的身份信息。
 * 原始角色资料仍是唯一身份来源，别名只提供指向它的入口。
 * 不请求网络、不让语言模型临时创造别名，也不修改原始记录。
 * 检索不把“看起来像某角色”转换成生成参数，最终使用的仍是原库触发词。
 * 名称表与候选筛选分离：名称负责召回，作品和外观条件负责限定范围。
 * Agent 的确认规则由调用方执行，本模块也服务需要分页的创建页。
 * 因此本模块只报告匹配层级，不自行弹窗、发送消息或提交工作流。
 */

// 莉音与 Rio 的对应关系来自本轮用户给出的“碧蓝档案 rio 莉音”。
// 塞尔达公主对应前面用户指定的 princess zelda 与作品资料。
// 只登记这些有明确依据的名称；没有登记的中文译名仍然可能查不到。
// 使用姓名和作品共同定位，未来出现同名角色时不会串到另一部作品。
// 每个别名可以关联多条资料，出现冲突时保留全部候选要求确认。
// 不为通用昵称如“公主”建立指向唯一角色的危险捷径。
// name 必须照抄资料中的标准标识，不能使用去括号后的显示名登记关系。
// work 同样使用原始作品字段，不能只凭作品翻译相似就绑定别名。
// 这是一份显式映射，不是完整中文角色词典；缺失项应通过后续资料维护补充。
// 修改别名需要随代码发布，当前工具不能在聊天中永久学习或写入新映射。
// 多个译名可放入 names，但不能把外观标签如 blonde 当成角色姓名。
// 资料删除后关联别名自然失效，不会留下没有原始角色的虚假候选。
const ALIASES = [
  { name: "rio (blue archive)", work: "blue archive", names: ["莉音"] },
  { name: "princess zelda", work: "the legend of zelda", names: ["塞尔达公主"] },
];

/** @typedef {import('./local-catalog').ReferenceRow} Row */
/** @typedef {{row:Row, names:string[]}} Entry */
/** @type {WeakMap<Row[], Entry[]>} 随原始数组释放，不保存用户查询。 */
// 缓存按资料数组登记，类似每一版通讯录都有自己的索引卡。
// 重新加载得到新数组时建立新卡片；不需要全局清空其他版本的索引。
// 这里只有名称数组和原记录引用，未额外缓存整份卡片或分类计数。
// 资料在加载后视为只读；原地改名不属于这个缓存支持的更新方式。
const indexes = new WeakMap();

/**
 * 全角字母、大小写和下划线属于输入形式差异，不属于角色身份差异。
 * 括号与作品后缀保留，避免两部作品的同名角色被强制合并。
 * 正常化只用于比较，展示与触发词仍返回资料里的原文。
 * 不处理拼音或自动翻译，因为它们需要另外维护可核实的别名资料。
 * NFKC 解决全角与半角输入，不能把音近、形近的不同汉字视为同名。
 * 仅压缩空白，不删除正常词间空格，所以词组仍可以用于分层查询。
 * 姓名后的作品括号保留到精确比较，只有最后的容错层才另取短名。
 * 作品筛选也调用同一函数，避免同一字符串在两个入口有不同大小写规则。
 * 参数来自已校验资料或查询对象，不在这里把对象强转为文字。
 * @param {string} value 用户输入或已验证的资料字段
 */
function characterKey(value) {
  return value.normalize("NFKC").trim().toLowerCase().replace(/_/g, " ").replace(/\s+/g, " ");
}

/**
 * 每份已加载资料只建立一次名称表，查询不反复处理八千条原始字符串。
 * WeakMap 按原数组身份缓存，测试或后续换库不会串用旧资料的索引。
 * 别名必须同时匹配标准名称和作品，孤立别名不会凭空生成新角色。
 * 名称表保留原记录引用，属性筛选和姓名检索因此使用同一个身份。
 * 内存表不包含用户路径、封面或 LoRA 文件，不扩张工具返回体积。
 * 不就地排序源数组，创建页的其他查询不会继承此次匹配顺序。
 * 别名归一化复用相同规则，避免只在一种输入写法下才能命中。
 * 这是规范化名称缓存，不是倒排索引；片段查询仍需检查当前候选。
 * 首次建立索引的成本随资料量增长，后续请求复用已处理的名称字符串。
 * 不缓存每个 query 的命中列表，因此没有无限积累用户查询的内存表。
 * 属性筛选先缩小 candidates，后面通过原记录引用快速排除其他记录。
 * 新别名只扩展对应行的 names，不增加角色总数或改变分类统计。
 * 同名原记录保留各自身份，不能按规范化名称去重后藏掉作品差异。
 * 资料字段由加载器验证，索引无需为每次查询重新解析 JSON。
 * 若将来支持用户维护别名，应在资料更新时更换索引身份而非就地改缓存。
 * @param {Row[]} rows 已校验的完整本地资料
 */
function characterIndex(rows) {
  let entries = indexes.get(rows);
  if (!entries) {
    // 标准名始终排第一，别名匹配层据此只查看后续登记名称。
    // 每行独立查映射，不把不同作品的同名记录共用一个别名数组。
    // 只规范化已收录映射，查询时不会临时向原资料添加用户提供的名字。
    // 索引的创建是同步纯计算，读取文件和异常恢复仍归资料加载器负责。
    entries = rows.map(row => ({ row, names: [characterKey(row.name), ...ALIASES
      .filter(alias => alias.name === row.name && alias.work === row.copyright)
      .flatMap(alias => alias.names.map(characterKey))] }));
    indexes.set(rows, entries);
  }
  return entries;
}

/**
 * 只容忍一次插入、删除或替换；不会把整个词义相近当成同一个角色。
 * 例如 princess 少写一个 s 可进入候选，两个以上错字不会继续扩大搜索。
 * 两个游标像核对两张名单，发现一次差异后跳过对应字母继续逐字核对。
 * 长度相同跳过双方，长度不同只跳过较长一方，覆盖缺字和多字。
 * 长度差大于一直接拒绝，避免为明显无关名字做不必要的比较。
 * 这只是候选召回，不是身份确认；调用方必须要求用户确认容错结果。
 * 中文短名字不在这一层纠错，单字差异可能就是另一个真实角色。
 * 字符比较使用已经规范化的拉丁输入，不试图计算语言发音的相似度。
 * 同长度不匹配会同时前进一步，所以一次替换不会被误算为两次差异。
 * 较长输入删除一个字母后重新比较，能区分缺字与后续位置全部错位。
 * 空余尾巴只能有一位，因为开头已拒绝长度差大于一的情况。
 * 已出现一次中间差异时若尾巴还有剩余，最终应判定为超过容忍范围。
 * 该算法空间固定，不为每个名字分配二维编辑距离表。
 * 时间随两串较短长度增长，查询长度上限保证它不会接受整段长提示词。
 * 它不返回“置信度百分比”，因为单次编辑距离不能证明真实角色身份。
 * 零次差异被允许，是为了让同一比较器可处理剥离作品后恰好相同的短名。
 * Unicode 的多字节长度不在这里推断；调用方把容错范围限制为拉丁字母。
 * 精确与别名层不受这一限制，已登记的中文名称仍可正常检索。
 * 拼写纠错不会把结果写回别名表，用户的一次错字不能污染以后的查询。
 * 比较过程没有 I/O 或可取消资源，失败只表示本次候选不符合容错条件。
 * @param {string} left 规范化查询
 * @param {string} right 规范化名称或姓名词
 */
function oneEditApart(left, right) {
  if (Math.abs(left.length - right.length) > 1) return false;
  // 游标分别跟随两份文字；差异计数跨越整个单词而不是逐段重置。
  // 末尾多出的字母不进入循环，退出后还需作为最后一次差异计算。
  // 返回 true 也可能是完全相同，分层搜索保证精确层会先处理这种输入。
  let a = 0;
  let b = 0;
  let differences = 0;
  while (a < left.length && b < right.length) {
    if (left[a] === right[b]) {
      a++;
      b++;
      continue;
    }
    // 第二个不同点已足以拒绝，不必继续计算完整编辑距离矩阵。
    // 相等长度按替换处理；多一字时让较短一方留在原位置重新比对。
    // 不支持相邻两字母交换，它涉及两个位置，超出本轮保守纠错范围。
    if (++differences > 1) return false;
    if (left.length >= right.length) a++;
    if (right.length >= left.length) b++;
  }
  return differences + Number(a < left.length || b < right.length) <= 1;
}

/**
 * 四层搜索共用已缓存的名称表，但只从当前属性允许的记录中选候选。
 * 精确名称优先于别名；别名优先于普通片段，避免热门近似项盖过明确输入。
 * 多词查询要求每个词都出现在该角色的标准名或已收录别名中。
 * 因此用户同时输入 rio 和莉音仍指向同一条资料，不用删词重复请求。
 * 容错只接受四至四十八位拉丁姓名及空格，限制耗时与误匹配范围。
 * 全空查询属于分类浏览，保留调用方已经筛过的全部候选。
 * 返回新数组供调用方排序，不能改写缓存顺序或候选资格。
 * 同一层的全部匹配都保留，不用排名或截断制造“唯一角色”。
 * 无结果仍标明 none，不能把最后一次猜测当成已经识别成功。
 * 精确层比较完整标准名，包含作品后缀时可直接消除某些同名歧义。
 * 别名层只接受整个已登记别名，不会把任意汉字拆开当作精确身份。
 * 片段层支持标准名和别名混合，例如英文名加一个已登记的中文译名。
 * 多词可以分别命中两种写法，但必须属于同一行记录。
 * Set 使用原记录引用判定资格，因此 candidates 必须来自这份原库。
 * 查询前已验证长度上限，此处另外限制容错层的拉丁字母范围。
 * 模糊层不把作品文字参与编辑距离，避免用户输错作品却找到同名人物。
 * 括号外短名与各个姓名词同时比较，支持漏掉姓氏的英文姓名输入。
 * 普通片段命中不会再进行纠错，减少无关相似名字进入候选。
 * 用词间包含关系召回不代表语义相似，更不表示角色外观可以互换。
 * 每层结果先保留全集，分页和按热度排列发生在调用方。
 * 查询 alice 可能返回多个人；上层必须按完整 total 判断是否唯一。
 * 源数组不被修改，后台另一次角色查询不会改变当前候选引用。
 * 这里不限制候选为一项，因为截断会把真实歧义隐藏起来。
 * 没有找到人物时不会回退到热门角色，也不会默认使用库里的第一项。
 * 容错阈值独立于候选热度，热门人物不会得到更多允许错字的机会。
 * 对短中文名采用保守策略，宁可要求补充英文名也不静默替换身份。
 * 返回 type 是应用内部判断依据，不能当作用户已经确认的记录。
 * @param {Row[]} rows 完整资料，作为索引的生命周期标识
 * @param {Row[]} candidates 已满足严格属性条件的候选
 * @param {string} text 角色名或浏览时的空字符串
 */
function matchCharacterRows(rows, candidates, text) {
  const query = characterKey(text);
  const allowed = new Set(candidates);
  const entries = characterIndex(rows).filter(entry => allowed.has(entry.row));
  // 层级判定发生在整个候选集上，不能按一条记录一次跑完四层。
  // 否则先遇到的热门近似记录可能抢在后面的标准名精确记录之前返回。
  // 将筛选器按层集中，确保所有精确名都检查完才考虑别名。
  const words = query.split(" ");
  const layers = [
    { type: "exact", test: (/** @type {Entry} */ entry) => characterKey(entry.row.name) === query },
    { type: "alias", test: (/** @type {Entry} */ entry) => entry.names.slice(1).includes(query) },
    { type: "partial", test: (/** @type {Entry} */ entry) => words.every(word => entry.names.some(name => name.includes(word))) },
    // 容错前先从每个名称剥离括号作品，再拆姓名词。
    // 不能先拆词再删括号，否则作品里的 archive 也可能被当成人名纠错。
    // 每个姓名同时保留全名和组成词，方便比较缺姓或全名中单处错字。
    { type: "fuzzy", test: (/** @type {Entry} */ entry) => /^[a-z ]{4,48}$/.test(query) && entry.names
      .map(name => name.replace(/\s*\([^)]*\)/g, "")).some(name => [name, ...name.split(" ")].some(value => oneEditApart(query, value))) },
  ];
  // 空查询不会进入 every 的空词命中路径，明确区分浏览与名字识别。
  // 返回 slice 即使没有过滤也建立新数组，让后面的排序不更改原始顺序。
  if (!query) return { type: "browse", rows: candidates.slice() };
  for (const layer of layers) {
    // 匹配时始终带回完整记录，不能只留下规范化名称丢掉原始触发词。
    // 同一层多项结果保留同一 type，调用方可用作品信息帮助用户选择。
    // 此处不按热度取第一项，因此不因资料排序变化悄悄更换同名人物。
    const matched = entries.filter(layer.test).map(entry => entry.row);
    if (matched.length) return { type: layer.type, rows: matched };
  }
  return { type: "none", rows: [] };
}

// 两个调用方共享同一算法，Agent 不再维护另一份名称搜索规则。
// 正常化也供作品条件比较使用，但不会提供翻译或自动替换作品能力。
module.exports = { characterKey, matchCharacterRows };
