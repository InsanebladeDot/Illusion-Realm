// 画布图片名称取文件主体，显示标签不携带后缀、目录或完整用户路径。
// 像相册照片下面的题签：文件名负责身份，题签只省略最后一个格式后缀。
// 中文、空格和主体中的点均保留，不把人物名字误当成模板编号。
// 这里只处理显示文字，不读取文件、不授权路径，也不改变磁盘上的内容。
// 导入、生成结果、节点标题和引用候选共用它，避免四处各自截取名字。
// 没有后缀的旧素材继续显示全名，不把最后一个字符误删。
// 以点开头但没有主体的名称不视为“只有扩展”，保留可辨认的原文。
// 同时接受 Windows 与斜杠路径，旧工程提供路径式 name 时也不暴露目录。
import type { CanvasData } from "./canvas-model";

// 名称例子：人物.png 显示“人物”，不会显示格式后缀。
// 名称例子：角色.正面.v2.webp 显示“角色.正面.v2”，主体中的点有实际意义。
// 名称例子：无后缀的“设定草稿”原样显示，不能凭素材类型猜一个后缀再删掉。
// 名称例子：目录形式的 C:/作品/角色.png 只显示最后一段“角色”。
// 取最后一段同时兼容路径分隔符，不使用平台 Node path，确保渲染层仍满足隔离边界。
// 单纯显示文件名时不校验设备保留名，真正提交文件改名仍由已有主进程服务判断。
// 不能用 split('.')[0]，否则人物名字或版本标识包含点时会被错误截短。
export function canvasFilePrefix(name: string): string {
  const file = name.split(/[\\/]/).at(-1) ?? name;
  const dot = file.lastIndexOf(".");
  return dot > 0 ? file.slice(0, dot) : file;
}

// 只有真实图片资产覆盖节点显示名，空图片节点仍保留用户自己的工作标题。
// 视频、音频、文字和场景节点的标题契约不在本次请求中改变。
// 已保存的老图片标题可能仍是“图片”，显示时即可读取文件主体，无需强制迁移工程。
// 图片损坏时依然显示文件名，解码是否成功不能决定节点身份。
// 不按当前选中状态改名，因此失焦、复制和切换主题不会闪回通用标题。
// 源文件变化后 title 自动来自新 media.name，不需要监听 DOM 或异步扫描目录。
// 实际文件改名成功才更换 media.name；未确认输入不会通过此函数污染显示。
export function canvasNodeTitle(data: CanvasData): string {
  return data.kind === "image" && data.media?.kind === "image" ? canvasFilePrefix(data.media.name) : data.title;
}
