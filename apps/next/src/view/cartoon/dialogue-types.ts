/** 漫画对话框的编辑数据：画布用自然像素，图层位置与文字排版由同一份参数驱动。 */
// 不复用漫画分镜的格子类型，因为气泡可以旋转、重叠，格子则负责裁切图片。
// 图层 id 属于实例，同一个模板添加多次也不会共享文字或位置。
// templateId 只引用固定模板，不允许用户输入任意资源路径。
// 文字方向明确为横排或竖排，不用“旋转90度”代替中文竖排。
// x、y 是气泡中心，以自然画布坐标记录，不受窗口缩放影响。
// width 是整个模板画片宽度，高度按640:400换算。
// 模板保留透明留白，文字区域使用该画片内部的固定安全范围。
// fontSize 同样是自然像素，缩放显示与导出保持相同字形大小。
// lineHeight 是倍率，spacing 是像素，不能混用两者的单位。
// alignment 决定每行起点，换行仍受模板安全区域限制。
// 颜色只来自内置配置或现有颜色选择器，不解释为 CSS 代码。
// rotation 是整体图层角度，文字和底框一起旋转。
// opacity 同时影响底框与文字，避免出现只把框变透明的误解。
// background 保存解码后的图片，失败导入不替换已经存在的画布。
// width/height 始终是实际导出尺寸，页面几何只负责等比显示。
// 未导入背景时仍允许在白画布编辑，不预置用户截图中的人物图。
// 内存历史保存纯数据，不把 DOM、事件或 Canvas 节点写入快照。
// 选择状态不在文档中，撤销内容不会把另一个工具的选中项带进来。
// 不新增用户文档字段，也不把静态模板复制到每份用户设置中。
// 类型只服务渲染侧，不增加 IPC 或主进程文件权限。
// 新实例的默认文案按当前语言取值，已有用户文本不会在换语言时被重写。
// 图片导入后的 data URL 自包含，不依赖文件路径继续存在。
// 本轮保留在页面内存；导出 PNG 是明确的用户动作。
// 模板与文档分开使搜索筛选不会删除画布上已经放置的图层。
// 不在工具间共享一个全局选中 id，多开页面也不会互相修改图层。
// 编辑类型不含任意 HTML，文字最终由 React 转义后进入 SVG。
export interface DialogueLayer {
  // id在作品中唯一；templateId可以重复，表示多份实例使用同一个轮廓。
  // x/y不是图片左上角，编辑器以中心放置、旋转和拖动整层。
  // 这种中心定义使旋转180度时层不会围绕左上角甩到另一个位置。
  // width只决定画片比例，不能被误当文字安全区宽度。
  // text存原始普通文字，换行符属于正文，不保存SVG片段或HTML样式。
  // fontSize和spacing保存像素数，lineHeight保存倍率，读写控件需分别使用单位。
  // direction不包含auto，因为本地工具不推断语言阅读方向。
  // align是固定英文枚举，显示中文标签后也不能把“居中”存入字段。
  // color使用CSS可接受颜色字符串，实际编辑入口由共享色板规范化。
  // rotation按角度值而非弧度保存，能直接用于SVG的rotate参数。
  // opacity正常范围为0到1，类型number本身不替代数值控件的范围校验。
  // 接口只提供编译期约束，未来工程导入仍需要运行时检查finite与边界。
  // 不包含模板说明，成品绘制不应把编辑帮助文案作为气泡正文。
  // 不包含天然层级数，数组顺序已经是唯一叠放顺序，避免两套层级冲突。
  id: string; templateId: string; x: number; y: number; width: number;
  text: string; fontSize: number; lineHeight: number; spacing: number;
  // fontId只引用内置离线目录，不接收任意字体URL或CSS规则。
  // 可选用于兼容旧的内存快照；没有值时保持原系统字体。
  // 选择某字体后随实例进入历史，不改变其他气泡的默认字体。
  fontId?: string;
  direction: "horizontal" | "vertical"; align: "left" | "center" | "right";
  color: string; rotation: number; opacity: number;
}
export interface DialogueDocument {
  // width/height对应最终PNG像素，与舞台可用CSS面积分开。
  // 当前默认1280乘720，导入背景后允许用其真实自然尺寸替换。
  // background为空串明确表示白色底纸，不代表图片正在加载。
  // background非空是已读取的数据URL，不含用户原绝对磁盘路径。
  // layers只保存已添加实例，不把模板查询结果或未确认悬停项写进来。
  // 当前没有version字段，因为此对象尚未作为独立工程格式落盘。
  // 若以后新增保存能力，不能将未标记的会话对象直接当稳定交换协议。
  // 不把history嵌回文档，否则每次快照会递归保存整份过去记录。
  width: number; height: number; background: string; layers: DialogueLayer[];
}
