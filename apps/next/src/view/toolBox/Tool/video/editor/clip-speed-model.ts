// 片段倍速改变工程占用长度，源文件与素材元数据始终不变。
// 像把同一卷胶片以不同速度走过放映机，源秒数仍相同，观众看到的时长会变化。
// 碰撞采用原时间轴的帧级半开区间判断，不另建一套近似秒数校验。
// 不自动挤开后续片段，也不为避免碰撞偷偷截短内容；失败保留全部原值。
import { hasTimelineOverlap, type LiveTimelineClip } from "./live-timeline-model";

// 先确认对象和锁，再处理数值；程序调用不能绕过属性输入框的范围限制。
// 源入点保持不动，源跨度按旧速度计算，避免连续改速度逐次丢失原素材长度。
// 最后一帧工程占位可能超过真实源末尾少量，源跨度以真实剩余时长封顶。
// 新出点向上取整到工程帧，至少保留一帧，绝不生成零长片段。
// 复制片段拥有自己的speed值，不需要改共享asset，也不会改变同源其他实例。
// 锁轨或同轨后邻居冲突返回null，由拥有工程状态的调用方给出原位错误反馈。
// 速度存放在片段记录，asset.duration仍表示文件本身长度，二者不能互相覆盖。
// 同一源的两个实例即使入点相同，也可以各自使用不同倍速。
// 没有写speed的旧片段按1处理，导入与历史会话无须先迁移才能正常播放。
// 速度范围0.25–4与预览0.25–4相乘，保持Chromium实际播放支持范围0.0625–16。
// 不允许零、负数、NaN或Infinity，倒放不能借负速度绕过当前能力边界。
// 范围验证位于纯模型，禁用输入框不是业务权限的唯一保护。
// fps用于工程量化，不能改成源fps，否则不同帧率素材在同一轨道不对齐。
// 源跨度等于旧工程时长乘旧速度，先还原内容量，再计算新的工程时长。
// sourceDuration减sourceIn是源剩余上限，末帧向上取整产生的占位不能变成虚构内容。
// 新时长向上取整到项目帧，完整源尾帧不会因倍速变化被提前丢掉。
// 至少一帧是工程合法区间门槛，极短源不能在时间线上退化成零宽对象。
// 片段start保持不变，倍率变化只改变out点，不把速度编辑变成整段移动。
// 不移动前后邻居，现阶段没有开启波纹编辑或自动让位的业务契约。
// 碰撞复用hasTimelineOverlap的半开帧区间，相邻端点恰好一致仍可合法接合。
// 检查时仍传入原数组，算法靠id排除自己，不能把同源邻居一起忽略。
// 减速导致冲突返回null，不返回一个部分成功且内容被缩短的候选。
// 锁表使用当前片段track，无论菜单、字段或未来快捷键都遵守同一规则。
// 成功时只替换目标片段对象，其他实例保持原引用，不无故重建全部素材。
// transform等既有字段通过展开保留，调整速度不能悄悄重置构图。
// 当前不处理音高保持选项，HTML媒体默认音高策略不等于专业变速重采样导出。
// 分离音轨有自己的实例；视频后续变速不自动改动已分离音轨的时间安排。
// 复制时speed随记录保留，后续再改副本也只替换副本。
// 错误由工程会话统一解释，不在纯模型里弹窗或写语言状态。
// 这条命令不创建文件、不调用FFmpeg转码，也不代表工程已经保存。
// 预览控制栏倍率不调用本函数，因此不会让工程长度跟着试听倍率变化。
// 这里按完整剩余源上限计算，不用封面文件的生成时间或图片尺寸当源时长。
// 旧速度参与源跨度还原，若忽略它，连续2倍再1倍会错误地越改越短。
// 保留至少一帧后再做碰撞检查，不能以零长候选躲过邻居验证。
// 邻居即便与当前片段同assetId也必须算障碍，内容相同不等于工程实例相同。
// 其他轨道上的覆盖是合法层叠，不应被当成减速冲突拒绝。
// 同轨恰好贴边属于合法半开区间，不需要额外留一帧空白。
// 速度改变后工程总长可能不变，例如后方另有更远片段；不能强制让总长等于本片段末尾。
// 本函数没有选择状态，因此纯模型不会因修改速度而替用户高亮所有同源实例。
// 数值保留两位由字段校验处理，模型仍验证有限值和范围防止程序旁路。
// 如果未来增加音频专用速度组，应复用时间映射并另行定义音高与混音能力边界。
export function changeClipSpeed(clips: readonly LiveTimelineClip[], id: string, speed: number, fps: number, locked: readonly string[]) {
  const clip = clips.find(item => item.id === id);
  if (!clip || locked.includes(clip.track) || !Number.isFinite(speed) || speed < .25 || speed > 4 || !Number.isFinite(fps) || fps <= 0) return null;
  const span = Math.min(clip.sourceDuration - clip.sourceIn, (clip.end - clip.start) * (clip.speed ?? 1));
  const next = { ...clip, speed, end: clip.start + Math.max(1, Math.ceil(span / speed * fps)) / fps };
  if (hasTimelineOverlap(clips, next, fps)) return null;
  return clips.map(item => item.id === id ? next : item);
}
