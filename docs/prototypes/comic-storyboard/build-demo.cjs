/** Generate offline lucide assets using the application's installed packages. */
const fs = require("fs");
const path = require("path");
const { createRequire } = require("module");
const appRequire = createRequire(path.resolve(__dirname, "../../../apps/next/package.json"));
const React = appRequire("react");
const { renderToStaticMarkup } = appRequire("react-dom/server");
const icons = appRequire("lucide-react");
const names = ["Undo2", "Redo2", "Download", "FileJson", "Upload", "RotateCcw", "ArrowUp", "ArrowDown", "Lock", "Unlock", "Scissors", "Combine", "Shuffle", "Maximize", "Route", "Settings2", "ImagePlus", "ChevronLeft"];
const values = Object.fromEntries(names.map(name => [name, renderToStaticMarkup(React.createElement(icons[name], { size: 18, strokeWidth: 1.7 }))]));
fs.writeFileSync(path.join(__dirname, "demo-icons.js"), "// Generated by build-demo.cjs.\nwindow.DEMO_ICONS = " + JSON.stringify(values) + ";\n");
console.log("Offline lucide icons generated.");
