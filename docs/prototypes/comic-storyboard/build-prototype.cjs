/** Embed repository fixtures so file:// preview and canvas export work offline. */
const fs = require("fs");
const path = require("path");
const manifest = require("./asset-manifest.json");
const layout = require("./diagonal-layout.json");
const images = Object.fromEntries(manifest.assets.map(asset => [
  asset.id,
  `data:image/png;base64,${fs.readFileSync(path.join(__dirname, asset.file)).toString("base64")}`,
]));
fs.writeFileSync(path.join(__dirname, "prototype-data.js"),
  `// Generated by build-prototype.cjs.\nwindow.PROTOTYPE_DATA = ${JSON.stringify({ layout, images })};\n`);
console.log("Offline prototype assets embedded.");
